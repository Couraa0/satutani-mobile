class MarketPriceModel {
  final String productName;
  final String category;
  final String emoji;
  final double currentPrice;
  final double aiPredictedPrice;
  final double weekAgoPrice;
  final double monthAgoPrice;
  final String unit;
  final String trend; // 'up', 'down', 'stable'
  final double changePercent;
  final String aiConfidence; // 'Tinggi', 'Sedang', 'Rendah'
  final String aiReason;
  final List<PriceHistory> priceHistory;

  const MarketPriceModel({
    required this.productName,
    required this.category,
    required this.emoji,
    required this.currentPrice,
    required this.aiPredictedPrice,
    required this.weekAgoPrice,
    required this.monthAgoPrice,
    required this.unit,
    required this.trend,
    required this.changePercent,
    required this.aiConfidence,
    required this.aiReason,
    required this.priceHistory,
  });
}

class PriceHistory {
  final String date;
  final double price;
  const PriceHistory({required this.date, required this.price});
}

