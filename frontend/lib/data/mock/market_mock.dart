  final double forecastPrice14d;
  final double forecastPrice30d;
  final String unit;
  final String forecastTrend; // 'up', 'down', 'stable'
  final double forecastChangePercent;
  final String demandLevel; // 'Tinggi', 'Sedang', 'Rendah'
  final String bestSellWindow;
  final String aiInsight;
  final String supplyOutlook;
  final double confidenceScore; // 0.0 - 1.0

  const MarketForecastModel({
    required this.productName,
    required this.emoji,
    required this.category,
    required this.currentPrice,
    required this.forecastPrice7d,
    required this.forecastPrice14d,
    required this.forecastPrice30d,
    required this.unit,
    required this.forecastTrend,
    required this.forecastChangePercent,
    required this.demandLevel,
    required this.bestSellWindow,
    required this.aiInsight,
    required this.supplyOutlook,
    required this.confidenceScore,
  });
}

